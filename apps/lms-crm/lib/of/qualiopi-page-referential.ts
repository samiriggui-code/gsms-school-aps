/**
 * Référentiel front Qualiopi — chaque path CRM → indicateurs / preuves / pages liées.
 * Source de vérité pour développer le front « double lecture » métier + Qualiopi.
 * Breadcrumbs = MENU_SIDEBAR ; ce fichier = contenu Qualiopi attendu sur la page.
 *
 * Aligné V9 + Prisma (`docs/QUALIOPI-PRISMA-MAPPING.md`).
 */

import { QUALIOPI_INDICATORS_V9 } from '@/lib/of/qualiopi-indicators';

export type QualiopiPageRole =
  | 'hub' /** landing section / module — agrège, ne produit pas la preuve */
  | 'writer' /** page qui crée / met à jour la preuve métier */
  | 'reader' /** page Qualiopi qui lit / évalue (classeur, passeport, couverture) */
  | 'support' /** support OPS sans indicateur direct (ou indirect faible) */
  | 'na'; /** hors scope Qualiopi typique */

export type QualiopiPageEntry = {
  path: string;
  /** Titre court (sinon repris du menu). */
  title: string;
  role: QualiopiPageRole;
  /** Codes Q-Ixx que cette page doit permettre de satisfaire. */
  indicators: string[];
  /** Ce que Qualiopi / l’auditeur doit pouvoir retrouver ici. */
  mustFind: string[];
  /** Modèles Prisma / Evidence attendus (hints). */
  evidenceHints: string[];
  /** Paths liés (amont / aval / même preuve). */
  relatedPaths: string[];
  /** true = page absente du menu ou à créer. */
  missingInApp?: boolean;
  /** true = pas encore de page.tsx (stub à poser). */
  needsStub?: boolean;
  notes?: string;
};

function indLabel(code: string): string {
  const row = QUALIOPI_INDICATORS_V9.find((i) => i.code === code);
  return row ? `${code} — ${row.label}` : code;
}

/** Lookup public pour UI. */
export function qualiopiIndicatorLabel(code: string): string {
  return indLabel(code);
}

