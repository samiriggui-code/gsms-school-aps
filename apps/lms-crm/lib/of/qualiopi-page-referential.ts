export function getQualiopiPageEntry(path: string): QualiopiPageEntry | undefined {
  const normalized = path.replace(/\/$/, '') || '/';
  return QUALIOPI_PAGE_REFERENTIAL.find((e) => e.path === normalized);
}

export function listMissingQualiopiPages(): QualiopiPageEntry[] {
  return QUALIOPI_PAGE_REFERENTIAL.filter((e) => e.missingInApp || e.needsStub);
}

export function listPagesForIndicator(code: string): QualiopiPageEntry[] {
  return QUALIOPI_PAGE_REFERENTIAL.filter((e) => e.indicators.includes(code));
}

export function listWriterPages(): QualiopiPageEntry[] {
  return QUALIOPI_PAGE_REFERENTIAL.filter((e) => e.role === 'writer');
}
